// The HB-2's ROM font: 8 x 8, uppercase only, which is what a 1992 machine's font
// was. A lowercase letter is drawn as its capital, and the manual says so rather
// than pretending otherwise.
//
// It lives in the machine, not in the window, because a program prints with `INT 1`
// whether or not a window is looking: the harness has to draw the same characters
// into the same framebuffer the glass would show. A font owned by the widget would
// make the machine's output a property of the display, which is the one thing this
// machine is not allowed to be.
//
// The glyphs are drawn as eight rows of eight bits, most significant bit leftmost,
// so a byte is a row and a row is eight pixels -- the same shape a sprite has.

#pragma once

#include <array>
#include <cstdint>

namespace timewarp::hb2 {

inline constexpr int kGlyphWidth = 8;
inline constexpr int kGlyphHeight = 8;
/// Space through `Z`. Below space, and above `Z`, a glyph is blank -- and so is a
/// lowercase letter's missing case, which is drawn as its capital.
inline constexpr std::uint8_t kFontFirst = 32;
inline constexpr std::uint8_t kFontLast = 90;

/// The glyph for `code`, eight bytes of eight pixels.
[[nodiscard]] inline const std::array<std::uint8_t, kGlyphHeight>& glyphFor(std::uint8_t code) {
    static const std::array<std::array<std::uint8_t, kGlyphHeight>,
                            static_cast<std::size_t>(kFontLast - kFontFirst + 1)>
        kGlyphs{{
            {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},  // space
            {0x18, 0x18, 0x18, 0x18, 0x18, 0x00, 0x18, 0x00},  // !
            {0x6C, 0x6C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},  // "
            {0x6C, 0x6C, 0xFE, 0x6C, 0xFE, 0x6C, 0x6C, 0x00},  // #
            {0x18, 0x7E, 0xC0, 0x7C, 0x06, 0xFC, 0x18, 0x00},  // $
            {0xC6, 0xCC, 0x18, 0x30, 0x60, 0xC6, 0x00, 0x00},  // %
            {0x78, 0xCC, 0xC8, 0x70, 0xDA, 0xCC, 0x76, 0x00},  // &
            {0x18, 0x18, 0x30, 0x00, 0x00, 0x00, 0x00, 0x00},  // '
            {0x18, 0x30, 0x60, 0x60, 0x60, 0x30, 0x18, 0x00},  // (
            {0x60, 0x30, 0x18, 0x18, 0x18, 0x30, 0x60, 0x00},  // )
            {0x00, 0x66, 0x3C, 0xFF, 0x3C, 0x66, 0x00, 0x00},  // *
            {0x00, 0x18, 0x18, 0x7E, 0x18, 0x18, 0x00, 0x00},  // +
            {0x00, 0x00, 0x00, 0x00, 0x18, 0x18, 0x30, 0x00},  // ,
            {0x00, 0x00, 0x00, 0x7E, 0x00, 0x00, 0x00, 0x00},  // -
            {0x00, 0x00, 0x00, 0x00, 0x00, 0x18, 0x18, 0x00},  // .
            {0x06, 0x0C, 0x18, 0x30, 0x60, 0xC0, 0x80, 0x00},  // /
            {0x7C, 0xC6, 0xCE, 0xD6, 0xE6, 0xC6, 0x7C, 0x00},  // 0
            {0x18, 0x38, 0x78, 0x18, 0x18, 0x18, 0x7E, 0x00},  // 1
            {0x7C, 0xC6, 0x06, 0x1C, 0x30, 0x60, 0xFE, 0x00},  // 2
            {0x7C, 0xC6, 0x06, 0x3C, 0x06, 0xC6, 0x7C, 0x00},  // 3
            {0x0C, 0x1C, 0x3C, 0x6C, 0xFE, 0x0C, 0x0C, 0x00},  // 4
            {0xFE, 0xC0, 0xFC, 0x06, 0x06, 0xC6, 0x7C, 0x00},  // 5
            {0x3C, 0x60, 0xC0, 0xFC, 0xC6, 0xC6, 0x7C, 0x00},  // 6
            {0xFE, 0xC6, 0x0C, 0x18, 0x30, 0x30, 0x30, 0x00},  // 7
            {0x7C, 0xC6, 0xC6, 0x7C, 0xC6, 0xC6, 0x7C, 0x00},  // 8
            {0x7C, 0xC6, 0xC6, 0x7E, 0x06, 0x0C, 0x78, 0x00},  // 9
            {0x00, 0x18, 0x18, 0x00, 0x18, 0x18, 0x00, 0x00},  // :
            {0x00, 0x18, 0x18, 0x00, 0x18, 0x18, 0x30, 0x00},  // ;
            {0x0C, 0x18, 0x30, 0x60, 0x30, 0x18, 0x0C, 0x00},  // <
            {0x00, 0x00, 0x7E, 0x00, 0x7E, 0x00, 0x00, 0x00},  // =
            {0x60, 0x30, 0x18, 0x0C, 0x18, 0x30, 0x60, 0x00},  // >
            {0x7C, 0xC6, 0x0C, 0x18, 0x18, 0x00, 0x18, 0x00},  // ?
            {0x7C, 0xC6, 0xDE, 0xDE, 0xDE, 0xC0, 0x78, 0x00},  // @
            {0x38, 0x6C, 0xC6, 0xC6, 0xFE, 0xC6, 0xC6, 0x00},  // A
            {0xFC, 0xC6, 0xC6, 0xFC, 0xC6, 0xC6, 0xFC, 0x00},  // B
            {0x7C, 0xC6, 0xC0, 0xC0, 0xC0, 0xC6, 0x7C, 0x00},  // C
            {0xF8, 0xCC, 0xC6, 0xC6, 0xC6, 0xCC, 0xF8, 0x00},  // D
            {0xFE, 0xC0, 0xC0, 0xF8, 0xC0, 0xC0, 0xFE, 0x00},  // E
            {0xFE, 0xC0, 0xC0, 0xF8, 0xC0, 0xC0, 0xC0, 0x00},  // F
            {0x7C, 0xC6, 0xC0, 0xCE, 0xC6, 0xC6, 0x7E, 0x00},  // G
            {0xC6, 0xC6, 0xC6, 0xFE, 0xC6, 0xC6, 0xC6, 0x00},  // H
            {0x7C, 0x38, 0x38, 0x38, 0x38, 0x38, 0x7C, 0x00},  // I
            {0x1E, 0x0C, 0x0C, 0x0C, 0xCC, 0xCC, 0x78, 0x00},  // J
            {0xC6, 0xCC, 0xD8, 0xF0, 0xD8, 0xCC, 0xC6, 0x00},  // K
            {0xC0, 0xC0, 0xC0, 0xC0, 0xC0, 0xC0, 0xFE, 0x00},  // L
            {0xC6, 0xEE, 0xFE, 0xD6, 0xC6, 0xC6, 0xC6, 0x00},  // M
            {0xC6, 0xE6, 0xF6, 0xDE, 0xCE, 0xC6, 0xC6, 0x00},  // N
            {0x7C, 0xC6, 0xC6, 0xC6, 0xC6, 0xC6, 0x7C, 0x00},  // O
            {0xFC, 0xC6, 0xC6, 0xFC, 0xC0, 0xC0, 0xC0, 0x00},  // P
            {0x7C, 0xC6, 0xC6, 0xC6, 0xD6, 0xCC, 0x76, 0x00},  // Q
            {0xFC, 0xC6, 0xC6, 0xFC, 0xD8, 0xCC, 0xC6, 0x00},  // R
            {0x7C, 0xC6, 0xC0, 0x7C, 0x06, 0xC6, 0x7C, 0x00},  // S
            {0xFE, 0x38, 0x38, 0x38, 0x38, 0x38, 0x38, 0x00},  // T
            {0xC6, 0xC6, 0xC6, 0xC6, 0xC6, 0xC6, 0x7C, 0x00},  // U
            {0xC6, 0xC6, 0xC6, 0xC6, 0xC6, 0x6C, 0x38, 0x00},  // V
            {0xC6, 0xC6, 0xC6, 0xD6, 0xFE, 0xEE, 0xC6, 0x00},  // W
            {0xC6, 0x6C, 0x38, 0x38, 0x6C, 0xC6, 0xC6, 0x00},  // X
            {0xC6, 0xC6, 0x6C, 0x38, 0x38, 0x38, 0x38, 0x00},  // Y
            {0xFE, 0x06, 0x0C, 0x38, 0x60, 0xC0, 0xFE, 0x00},  // Z
        }};

    // Lowercase is the capital, because the ROM font has one case and a program that
    // prints "Hello" should read as "HELLO" rather than as three blanks and an "L".
    if (code >= 'a' && code <= 'z') {
        code = static_cast<std::uint8_t>(code - 'a' + 'A');
    }
    if (code < kFontFirst || code > kFontLast) {
        return kGlyphs[0];
    }
    return kGlyphs[static_cast<std::size_t>(code - kFontFirst)];
}

}  // namespace timewarp::hb2
