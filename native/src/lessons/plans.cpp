// The lesson plans, rendered from the curriculum.
//
// `docs/lessons/plans/` is generated, not written: two copies of a lesson drift,
// and the one that drifts is always the one being read. This is the renderer, and
// `time_warp_teach plans --write` is the only thing that calls it.
//
// #### Why the prose is escaped
//
// Lesson prose is *about* programming languages, so it contains asterisks,
// underscores, backticks and lines beginning with `+` -- every one of which
// Markdown reads as formatting. `6 * 7` opened an emphasis span that ran to the
// next asterisk in the paragraph, and a hint reading `+ adds its arguments.`
// became a nested list. `plain()` escapes here rather than in the curriculum, so
// the terminal plan (`time_warp_teach plans`) still prints the words as written
// while the document renders them as written.
//
// The output is byte-identical to what the reference tool produced, because
// `.github/workflows/docs.yml` regenerates it and refuses a diff: a renderer that
// "looks the same" and differs by a space would fail that check at release time
// rather than here.

